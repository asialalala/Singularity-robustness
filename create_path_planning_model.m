function create_path_planning_model()
%CREATE_PATH_PLANNING_MODEL Create the selectable Jacobian Simulink example.

model = 'jacobian_path_planning';
modelFile = fullfile(fileparts(mfilename('fullpath')), [model '.slx']);
if bdIsLoaded(model)
    close_system(model, 0);
end
if isfile(modelFile)
    delete(modelFile);
end

assignin('base', 'L1', 1.0);
assignin('base', 'L2', 0.8);
assignin('base', 'a0', 0.2);
assignin('base', 'a1', 0.6);
assignin('base', 'a2', 0.5);
assignin('base', 'a3', 0.35);
assignin('base', 'initial_q', [0; 0; 0]);
assignin('base', 'target', [1.25; 0.65; 0.2]);
assignin('base', 'Kp', 2.0);
assignin('base', 'max_joint_speed', 1.5);
assignin('base', 'simulation_time', 8.0);
assignin('base', 'model_selection', 1);
assignin('base', 'algorithm_selection', 1);

new_system(model);
set_param(model, 'StopTime', 'simulation_time', 'Solver', 'ode45', ...
    'ReturnWorkspaceOutputs', 'on');

add_constant(model, 'Target', 'target', [30 70 95 100]);
add_constant(model, 'Model Selection', 'model_selection', [30 125 95 155]);
add_constant(model, 'Algorithm Selection', 'algorithm_selection', [30 180 95 210]);
add_constant(model, 'L1', 'L1', [30 250 95 280]);
add_constant(model, 'L2', 'L2', [30 300 95 330]);
add_constant(model, 'a0', 'a0', [30 350 95 380]);
add_constant(model, 'a1', 'a1', [30 400 95 430]);
add_constant(model, 'a2', 'a2', [30 450 95 480]);
add_constant(model, 'a3', 'a3', [30 500 95 530]);
add_constant(model, 'Kp', 'Kp', [30 550 95 580]);
add_constant(model, 'Max Joint Speed', 'max_joint_speed', [30 600 95 630]);

add_block('simulink/Discrete/Unit Delay', [model '/Joint State'], ...
    'InitialCondition', 'initial_q', 'SampleTime', '0.01', ...
    'Position', [840 35 890 75]);

create_algorithm_blocks(model);
create_model_blocks(model);

% Algorithm selector: control, damped planner, pseudoinverse planner.
add_line(model, 'Algorithm Selection/1', 'Algorithm Selector/1');
add_line(model, 'Damped Jacobian/1', 'Algorithm Selector/2');
add_line(model, 'Pseudoinverse Jacobian/1', 'Algorithm Selector/3');
add_line(model, 'Algorithm Selector/1', 'Two-Link Arm/1');
add_line(model, 'Algorithm Selector/1', 'Three-Joint Arm/1');
wire_model_inputs(model, 'Two-Link Arm');
wire_model_inputs(model, 'Three-Joint Arm');

% Model selector: control, two-link q/position and three-joint q/position.
add_line(model, 'Model Selection/1', 'Model Selector q/1');
add_line(model, 'Two-Link Arm/1', 'Model Selector q/2');
add_line(model, 'Three-Joint Arm/1', 'Model Selector q/3');
add_line(model, 'Model Selection/1', 'Model Selector position/1');
add_line(model, 'Two-Link Arm/2', 'Model Selector position/2');
add_line(model, 'Three-Joint Arm/2', 'Model Selector position/3');

add_line(model, 'Model Selector q/1', 'Joint State/1');
add_line(model, 'Joint State/1', 'Damped Jacobian/1');
add_line(model, 'Joint State/1', 'Pseudoinverse Jacobian/1');
wire_planner_inputs(model, 'Damped Jacobian');
wire_planner_inputs(model, 'Pseudoinverse Jacobian');

add_block('simulink/Sinks/To Workspace', [model '/q log'], ...
    'VariableName', 'q_log', 'SaveFormat', 'Structure With Time', ...
    'MaxDataPoints', 'inf', 'Position', [1030 120 1140 150]);
add_block('simulink/Sinks/To Workspace', [model '/End Effector log'], ...
    'VariableName', 'end_effector_log', 'SaveFormat', 'Structure With Time', ...
    'MaxDataPoints', 'inf', 'Position', [1030 220 1170 250]);
add_block('simulink/Sinks/Scope', [model '/End Effector Scope'], ...
    'Position', [1030 290 1170 330]);
add_line(model, 'Model Selector q/1', 'q log/1');
add_line(model, 'Model Selector position/1', 'End Effector log/1');
add_line(model, 'Model Selector position/1', 'End Effector Scope/1');

set_param(model, 'InitFcn', 'initial_q = evalin(''base'', ''initial_q'');');
save_system(model, modelFile);
close_system(model, 0);
fprintf('Created %s\n', modelFile);
end

function add_constant(model, name, value, position)
add_block('simulink/Sources/Constant', [model '/' name], ...
    'Value', value, 'Position', position);
end

function create_algorithm_blocks(model)
names = {'Damped Jacobian', 'Pseudoinverse Jacobian'};
codes = {planner_damped_code(), planner_pseudoinverse_code()};
ys = [90 390];
for index = 1:2
    block = add_block('simulink/User-Defined Functions/MATLAB Function', ...
        [model '/' names{index}], 'Position', [250 ys(index) 480 ys(index)+180]);
    set_matlab_function_code(block, codes{index});
end
add_block('simulink/Signal Routing/Multiport Switch', [model '/Algorithm Selector'], ...
    'DataPortOrder', 'One-based contiguous', 'Inputs', '3', ...
    'Position', [560 180 650 280]);
end

function create_model_blocks(model)
names = {'Two-Link Arm', 'Three-Joint Arm'};
codes = {two_link_code(), three_joint_code()};
ys = [90 390];
for index = 1:2
    block = add_block('simulink/User-Defined Functions/MATLAB Function', ...
        [model '/' names{index}], 'Position', [250 ys(index) 480 ys(index)+180]);
    set_matlab_function_code(block, codes{index});
end
add_block('simulink/Signal Routing/Multiport Switch', [model '/Model Selector q'], ...
    'DataPortOrder', 'One-based contiguous', 'Inputs', '3', ...
    'Position', [700 120 790 190]);
add_block('simulink/Signal Routing/Multiport Switch', [model '/Model Selector position'], ...
    'DataPortOrder', 'One-based contiguous', 'Inputs', '3', ...
    'Position', [700 240 790 310]);
end

function wire_planner_inputs(model, block)
ports = {'Target', 'Model Selection', 'L1', 'L2', 'a0', 'a1', 'a2', ...
    'a3', 'Kp', 'Max Joint Speed'};
for index = 1:numel(ports)
    add_line(model, [ports{index} '/1'], [block '/' num2str(index + 1)]);
end
end

function wire_model_inputs(model, block)
ports = {'L1', 'L2', 'a0', 'a1', 'a2', 'a3'};
for index = 1:numel(ports)
    add_line(model, [ports{index} '/1'], [block '/' num2str(index + 2)]);
end
add_line(model, 'Joint State/1', [block '/2']);
end

function set_matlab_function_code(block, code)
chart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', getfullname(block));
if isempty(chart)
    error('Could not access MATLAB Function block: %s', getfullname(block));
end
chart.Script = code;
end

function code = planner_damped_code()
code = planner_code(['lambda = 0.05;' newline ...
    'q_dot_task = J'' * ((J*J'' + lambda^2*eye(size(J,1))) \ command);']);
end

function code = planner_pseudoinverse_code()
code = planner_code('q_dot_task = pinv(J) * command;');
end

function code = planner_code(solve_line)
code = sprintf([ ...
    'function q_dot = planner(q, target, model_selection, L1, L2, a0, a1, a2, a3, Kp, max_joint_speed)\n' ...
    '%%#codegen\n' ...
    'position = zeros(3,1); J = zeros(3,3);\n' ...
    'if model_selection == 1\n' ...
    '    q12 = q(1:2);\n' ...
    '    position(1:2) = two_link_position(q12, L1, L2);\n' ...
    '    J(1:2,1:2) = two_link_jacobian(q12, L1, L2);\n' ...
    'else\n' ...
    '    position = three_joint_position(q, a0, a1, a2, a3);\n' ...
    '    J = three_joint_jacobian(q, a0, a1, a2, a3);\n' ...
    'end\n' ...
    'error = target - position;\n' ...
    'command = Kp * error;\n' ...
    '%s\n' ...
    'q_dot = q_dot_task;\n' ...
    'q_dot = min(max(q_dot, -max_joint_speed), max_joint_speed);\n' ...
    'end\n' ...
    '\n' ...
    'function position = two_link_position(q, L1, L2)\n' ...
    'position = [L1*cos(q(1))+L2*cos(q(1)+q(2)); L1*sin(q(1))+L2*sin(q(1)+q(2))];\n' ...
    'end\n' ...
    '\n' ...
    'function J = two_link_jacobian(q, L1, L2)\n' ...
    'J = [-L1*sin(q(1))-L2*sin(q(1)+q(2)), -L2*sin(q(1)+q(2)); ...\n' ...
    '     L1*cos(q(1))+L2*cos(q(1)+q(2)), L2*cos(q(1)+q(2))];\n' ...
    'end\n' ...
    '\n' ...
    'function position = three_joint_position(q, a0, a1, a2, a3)\n' ...
    'A = a1+a2*cos(q(2))+a3*cos(q(2)+q(3));\n' ...
    'position = [cos(q(1))*A; sin(q(1))*A; a0+a2*sin(q(2))+a3*sin(q(2)+q(3))];\n' ...
    'end\n' ...
    '\n' ...
    'function J = three_joint_jacobian(q, a0, a1, a2, a3)\n' ...
    'h = 1e-6; J = zeros(3,3);\n' ...
    'for k = 1:3\n' ...
    '    qp=q; qm=q; qp(k)=qp(k)+h; qm(k)=qm(k)-h;\n' ...
    '    J(:,k)=(three_joint_position(qp,a0,a1,a2,a3)-three_joint_position(qm,a0,a1,a2,a3))/(2*h);\n' ...
    'end\n' ...
    'end\n'], solve_line);
end

function code = two_link_code()
code = sprintf([ ...
    'function [q, position] = two_link_model(q_dot, q_previous, L1, L2, a0, a1, a2, a3)\n' ...
    '%%#codegen\n' ...
    'q=q_previous+0.01*q_dot; q(3)=0;\n' ...
    'position=[L1*cos(q(1))+L2*cos(q(1)+q(2)); L1*sin(q(1))+L2*sin(q(1)+q(2)); 0];\n' ...
    'end\n']);
end

function code = three_joint_code()
code = sprintf([ ...
    'function [q, position] = three_joint_model(q_dot, q_previous, L1, L2, a0, a1, a2, a3)\n' ...
    '%%#codegen\n' ...
    'q=q_previous+0.01*q_dot;\n' ...
    'A=a1+a2*cos(q(2))+a3*cos(q(2)+q(3));\n' ...
    'position=[cos(q(1))*A; sin(q(1))*A; a0+a2*sin(q(2))+a3*sin(q(2)+q(3))];\n' ...
    'end\n']);
end
